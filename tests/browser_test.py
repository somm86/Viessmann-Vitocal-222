"""Chromium integration using module-rendered HTML and simulated void Symcon SDK."""
import copy
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
html=(ROOT/'tests/output/tile.html').read_text()
snapshot=json.loads((ROOT/'tests/output/snapshot.json').read_text())
archived=json.loads((ROOT/'tests/output/history.json').read_text())
checks=0
def check(condition,message):
    global checks
    assert condition,message
    checks+=1
with sync_playwright() as p:
    options={'headless':True}
    if os.environ.get('CHROMIUM_PATH'): options['executable_path']=os.environ['CHROMIUM_PATH']
    browser=p.chromium.launch(**options)
    page=browser.new_page(viewport={'width':1200,'height':1100},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(html)
    page.clock.install()
    check(page.locator('#roomTargetInput').count()==1,'room target input present')
    check(page.locator('.plant, .plant-viewport').count()==0,'no plant schema')
    check(page.locator('#applyRoomTarget').is_enabled(),'room control action enabled')
    check(page.locator('.temperature-cards [data-history]').count()==4,'four clickable temperatures')
    check(page.locator('#water').inner_text()=='45,6 °C','water reading')
    check(page.locator('.energy-cards [data-history]').count()==3,'three clickable electrical cards')
    check(page.locator('#power').inner_text()=='2,60 kW','normalized power displayed')
    check(page.locator('#total').inner_text()=='1.250 kWh','total energy displayed')
    check(page.locator('#month').inner_text()=='50,0 kWh','calendar month consumption displayed')
    check(page.locator('#modeChoices button').count()==2,'operating mode selection present')
    check(page.locator('#modeChoices button[data-value="heating"]').get_attribute('aria-pressed')=='true','current source mode highlighted')
    check(page.locator('#modeBadge').inner_text()=='Heizen + Warmwasser','read-only operating-mode status')
    page.locator('[data-history="water"]').click()
    check(page.locator('#historyDialog').is_visible(),'history dialog opens')
    check('nur in der Symcon' in page.locator('#historyState').inner_text(),'SDK missing explained')
    page.locator('#closeHistory').click()
    page.evaluate("() => { window.calls=[]; window.requestAction=(ident,value)=>{calls.push({ident,value});}; }")
    confirmed=copy.deepcopy(snapshot);confirmed['values']['mode'].update(value='water',formatted='Nur Warmwasser')
    page.evaluate('handleMessage',json.dumps(confirmed))
    check(page.locator('#modeBadge').inner_text()=='Nur Warmwasser','read-only mode follows source updates')
    page.locator('[data-history="water"]').click()
    def request():
        call=page.evaluate('calls.at(-1)')
        check(call['ident']=='RequestHistory','history uses SDK')
        return json.loads(call['value'])
    def reply(req,points=None,error='',resolution='raw'):
        payload=dict(kind='history',error=error,points=points or [],resolution=resolution,**req)
        page.evaluate('handleMessage',json.dumps(payload))
    req=request()
    check(req['key']=='water' and req['end']-req['start']==86400,'24 hour default request')
    check(page.locator('#historyNext').is_disabled(),'cannot navigate into future')
    # Use points actually returned through PHP/ArchiveControl in module tests.
    points=archived['points']
    reply(req,points)
    check(page.locator('#historyChart .chart-line').count()==1,'archive graph drawn')
    check(page.locator('#historyTable tr').count()==3,'accessible archive value table')
    check('Einzelwerte' in page.locator('#historySummary').inner_text(),'raw samples labelled')
    page.locator('#historyChart').hover(position={'x':300,'y':120})
    check(page.locator('#chartTooltip').is_visible(),'hover shows dated measurement')
    page.locator('#historyChart').dispatch_event('pointerleave')
    page.locator('#historyChart').dispatch_event('pointerdown',{'clientX':300})
    check(page.locator('#chartTooltip').is_visible(),'touch pointer selects measurement')
    page.locator('#historyPrev').click();previous=request()
    check(previous['end']==req['start'] and previous['end']-previous['start']==86400,'back shifts complete window')
    check(page.locator('#historyNext').is_enabled(),'forward available in past')
    check(page.locator('#historyChart .chart-line').count()==0,'old plot cleared during load')
    reply(req,points)
    check(page.locator('#historyChart .chart-line').count()==0,'stale response ignored')
    page.locator('#historyNext').click();following=request()
    check(following['start']==req['start'] and following['end']==req['end'],'forward returns to original window')
    reply(following,points)
    page.locator('#historyRange').select_option('604800');week=request()
    check(week['end']-week['start']==604800,'7 day selection')
    reply(week,[{'time':week['start']+3600,'value':25.0}],resolution='hourly')
    check('Stundenmittelwerte' in page.locator('#historySummary').inner_text(),'aggregation labelled')
    check(page.locator('#historyChart .chart-point').count()==1,'single point visible')
    page.locator('#historyRange').select_option('2592000');month=request()
    check(month['end']-month['start']==2592000,'30 day selection')
    reply(month,[])
    check('Keine archivierten Werte' in page.locator('#historyState').inner_text(),'empty archive explained')
    check(page.locator('#historyChart .chart-line').count()==0,'empty archive never faked')
    page.locator('#historyNow').click();now=request()
    reply(now,error='Keine aktive Archivierung für Variable 56634.')
    check('Keine aktive Archivierung' in page.locator('#historyState').inner_text(),'archive error visible')
    check(page.locator('#feedback').inner_text()=='','history errors stay in dialog')
    page.locator('#historyRange').select_option('3600');hour=request()
    check(hour['end']-hour['start']==3600,'1 hour selection')
    page.clock.fast_forward(16000)
    check('Keine Antwort' in page.locator('#historyState').inner_text(),'history timeout')
    reply(hour,[{'time':hour['start']+100,'value':20}])
    check(page.locator('#historyChart .chart-line').count()==0,'response after timeout ignored')
    page.locator('#historyNow').click();late=request()
    page.keyboard.press('Escape')
    check(not page.locator('#historyDialog').is_visible(),'escape closes dialog')
    page.locator('[data-history="flow"]').focus();page.keyboard.press('Enter');flow=request()
    check(flow['key']=='flow','temperature keyboard activation')
    reply(late,points)
    check(page.locator('#historyChart .chart-line').count()==0,'response from closed dialog ignored')
    reply(flow,[{'time':flow['start']+100,'value':27.0},{'time':flow['end']-10,'value':28.5}])
    check(page.locator('#historyTitle').inner_text()=='Vorlauf Sekundär','correct temperature title')
    check(page.locator('#historyChart .chart-line').count()==1,'reopened chart works')
    page.locator('#closeHistory').click()
    for key in ['primaryFlow','return']:
        page.locator(f'[data-history="{key}"]').click();r=request();check(r['key']==key,'correct source '+key);page.locator('#closeHistory').click()
    page.evaluate('handleMessage',snapshot)
    check(all(c['ident']=='RequestHistory' for c in page.evaluate('calls')),'browser only requests read-only history')
    page.locator('main').screenshot(path=str(ROOT/'docs/dashboard.png'))
    for width in [320,390,768,1200]:
        page.set_viewport_size({'width':width,'height':1000})
        check(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),'dashboard no horizontal overflow '+str(width))
        page.locator('[data-history="water"]').click();r=request()
        synthetic=[{'time':r['start']+int((r['end']-r['start'])*i/24),'value':44+(i%6)*.4} for i in range(25)]
        reply(r,synthetic)
        check(page.locator('#historyDialog').evaluate('(d)=>d.scrollWidth<=d.clientWidth'),'dialog no horizontal overflow '+str(width))
        check(page.locator('#historyPrev').is_visible() and page.locator('#historyRange').is_visible(),'navigation reachable '+str(width))
        if width==1200: page.screenshot(path=str(ROOT/'docs/history.png'),full_page=True)
        page.locator('#closeHistory').click()
    # Height-only and simultaneous viewport changes must refit without reloading.
    for width,height in [(1200,220),(640,220),(320,260),(800,160),(320,480),(1800,180),(240,150),(1200,1100)]:
        page.set_viewport_size({'width':width,'height':height})
        page.wait_for_function("document.querySelector('main').getBoundingClientRect().bottom<=innerHeight && document.querySelector('main').getBoundingClientRect().right<=innerWidth+.5")
        bounds=page.evaluate("""() => Array.from(document.querySelectorAll('main,main header,main .panel,main footer,main [data-history]')).map(el=>{
            const r=el.getBoundingClientRect();return {left:r.left,top:r.top,right:r.right,bottom:r.bottom};
        })""")
        check(all(r['left']>=-.5 and r['top']>=-.5 and r['right']<=width+.5 and r['bottom']<=height+.5 for r in bounds),'complete tile fits '+str((width,height)))
        check(page.evaluate('document.documentElement.scrollHeight<=innerHeight && document.documentElement.scrollWidth<=innerWidth'),'no viewport scrolling '+str((width,height)))
    page.wait_for_function("Number(document.querySelector('main').style.getPropertyValue('--tile-scale'))===1")
    check(page.locator('main').evaluate("el=>Number(el.style.getPropertyValue('--tile-scale'))")==1,'growing restores original scale')
    page.set_viewport_size({'width':800,'height':220});page.wait_for_function("document.querySelector('main').getBoundingClientRect().bottom<=innerHeight")
    grown=copy.deepcopy(snapshot)
    grown['missing']=['Warmwasser Ist','Vorlauf Primärquelle','Rücklauf Sekundär']
    grown['values']['mode']['formatted']='Eine längere Betriebsartbeschreibung mit zusätzlichem Status aus der Quellvariable'
    page.evaluate('handleMessage',grown);page.wait_for_function("document.querySelector('main').getBoundingClientRect().bottom<=innerHeight")
    check(page.locator('main').evaluate('(el)=>el.getBoundingClientRect().bottom<=innerHeight'),'long live values trigger refit')
    page.evaluate('handleMessage',snapshot);page.clock.run_for(120)
    page.locator('[data-history="water"]').click();scaled_request=request()
    reply(scaled_request,[{'time':scaled_request['start']+100,'value':44.5}])
    check(page.locator('#historyChart .chart-point').count()==1,'scaled temperature button opens usable history')
    check(page.locator('#historyDialog').evaluate('(el)=>el.getBoundingClientRect().height<=innerHeight'),'history dialog fits short tile independently')
    page.locator('#closeHistory').click()
    # Resizing a containing tile/iframe must work without changing the outer window.
    host=browser.new_page(viewport={'width':1200,'height':900})
    host.set_content('<iframe id="tile" style="width:800px;height:500px;border:0"></iframe>')
    frame=host.frames[1];frame.set_content(html)
    host.locator('#tile').evaluate("el=>el.style.height='180px'")
    frame.wait_for_function("document.querySelector('main').getBoundingClientRect().bottom<=innerHeight")
    check(frame.evaluate("document.querySelector('footer').getBoundingClientRect().bottom<=180"),'parent iframe height change refits content')
    host.locator('#tile').evaluate("el=>el.style.height='1200px'")
    frame.wait_for_function("Number(document.querySelector('main').style.getPropertyValue('--tile-scale'))===1")
    check(frame.evaluate("document.querySelector('main').getBoundingClientRect().bottom<=innerHeight"),'parent iframe grows without stale small scale')
    host.close()
    page.set_viewport_size({'width':1200,'height':1100});page.clock.run_for(120)
    page.locator('#modeChoices button[data-value="water"]').click()
    check(page.evaluate('calls[calls.length-1]')=={'ident':'ChangeMode','value':'water'},'mode control dispatches selected source value')
    check(page.locator('#modeChoices button[data-value="heating"]').get_attribute('aria-pressed')=='true','mode selection waits for device acknowledgement')
    for key in ['roomTarget','waterTarget']:
        values=page.locator('#'+key+'Input option').evaluate_all('(options)=>options.filter(o=>o.value!=="").map(o=>Number(o.value))')
        check(len(values)>1 and all(values[i+1]-values[i]==1 for i in range(len(values)-1)),'temperature dropdown uses one degree steps '+key)
    page.locator('#roomTargetInput').select_option('23');page.locator('#applyRoomTarget').click()
    check(page.evaluate('calls[calls.length-1]')=={'ident':'SetRoomTarget','value':23},'room target dispatches numeric value')
    page.locator('#waterTargetInput').select_option('51');page.locator('#applyWaterTarget').click()
    check(page.evaluate('calls[calls.length-1]')=={'ident':'SetWaterTarget','value':51},'water target dispatches numeric value')
    page.evaluate('handleMessage',{'kind':'control','action':'SetRoomTarget','error':'Quellaktion fehlgeschlagen'})
    check(page.locator('#feedback').inner_text()=='Quellaktion fehlgeschlagen','source action error displayed')
    disabled=copy.deepcopy(snapshot);disabled['controls']['waterTarget'].update(enabled=False,reason='Keine Variablenaktion')
    page.evaluate('handleMessage',disabled)
    check(page.locator('#waterTargetInput').is_disabled() and page.locator('#applyWaterTarget').is_disabled(),'missing source action disables water control')
    no_options=copy.deepcopy(snapshot);no_options['controls']['mode']['options']=[]
    page.evaluate('handleMessage',no_options)
    check(page.locator('#modeInput').is_visible() and page.locator('#modeChoices').is_hidden(),'mode without source options uses exact-value input')
    page.evaluate('handleMessage',snapshot)
    for key,unit,values in [('power','kW',[2.0,2.6]),('total','kWh',[2.0,3.0]),('month','kWh',[.5,1.5])]:
        page.locator(f'[data-history="{key}"]').click();energy_request=request()
        check(energy_request['key']==key,'correct electrical history target '+key)
        points=[{'time':energy_request['start']+100,'value':values[0]},{'time':energy_request['end']-1,'value':values[1]}]
        reply(energy_request,points,resolution='consumptionDaily' if key=='month' else 'consumptionHourly' if key=='total' else 'raw')
        if not page.locator('#historyDialog details').evaluate('(el)=>el.open'):
            page.locator('#historyDialog details summary').click()
        check(unit in page.locator('#historyUnitHeading').inner_text(),'energy table unit '+key)
        check(unit in page.locator('#historySummary').inner_text() and '°C' not in page.locator('#historySummary').inner_text(),'energy graph units '+key)
        if key!='power': check(('Tagesverbrauch' if key=='month' else 'Stundenverbrauch') in page.locator('#historySummary').inner_text() and 'je Archivintervall' in page.locator('#historySummary').inner_text(),'counter interval consumption labelled '+key)
        page.locator('#historyChart').hover(position={'x':300,'y':120})
        check(unit in page.locator('#chartTooltip').inner_text(),'energy tooltip unit '+key)
        if key=='month':
            points[1]['breakBefore']=True
            page.locator('#historyNow').click();month_request=request();reply(month_request,points,resolution='monthly')
            check(page.locator('#historyChart .chart-bar').count()==2 and page.locator('#historyChart .chart-line').count()==0,'monthly values use independent bars')
        page.locator('#closeHistory').click()
    for key in ['compressor','valve']:
        page.locator(f'[data-history="{key}"]').click();status_request=request()
        reply(status_request,[{'time':status_request['start'],'value':0},{'time':status_request['end']-100,'value':1}],resolution='status')
        check(page.locator('#historyChart .chart-bar').count()==2 and page.locator('#historyChart .chart-line').count()==0,'boolean status bars '+key)
        check(('Warmwasser' if key=='valve' else 'An') in page.locator('#historyChart').text_content(),'status labels '+key)
        page.locator('#closeHistory').click()
    electrical_update=copy.deepcopy(snapshot);electrical_update['energy']['power']['value']=3.1
    page.evaluate('handleMessage',electrical_update)
    check(page.locator('#power').inner_text()=='3,10 kW','live electrical update')
    unconfigured=copy.deepcopy(snapshot);unconfigured['energy']['power'].update(value=None,reason='Quellvariable auswählen')
    page.evaluate('handleMessage',unconfigured)
    check(page.locator('#power').inner_text()=='—' and 'Quellvariable' in page.locator('#powerReason').inner_text(),'unconfigured electrical source is not zero')
    page.evaluate('handleMessage',snapshot)
    malicious=copy.deepcopy(snapshot);malicious['values']['mode']['formatted']='<img src=x onerror="window.injected=true">'
    page.evaluate('handleMessage',malicious)
    check(page.locator('#modeBadge img').count()==0,'mode captions escaped')
    unavailable=copy.deepcopy(snapshot);unavailable['missing']=['Warmwasser Ist'];unavailable['values']['water'].update(value=None,formatted='—')
    page.evaluate('handleMessage',unavailable)
    check(page.locator('#water').inner_text()=='—','missing source never zero')
    check(not errors,'no browser errors: '+str(errors))
    browser.close()
print(f'PASS: {checks} browser assertions')
